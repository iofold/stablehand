#!/bin/sh
# ── CTXMill Egress Proxy Entrypoint ──────────────────────────────────────────
#
# Generates the nginx stream map from either:
#   1. CTXMILL_ALLOWED_EGRESS_DOMAINS env var (comma-separated), or
#   2. /etc/nginx/allowed-domains.conf (one domain per line)
#
# Then starts nginx in the foreground.
# ─────────────────────────────────────────────────────────────────────────────

set -e

DOMAINS_FILE="/etc/nginx/allowed-domains.conf"
MAP_FILE="/etc/nginx/stream-map.conf"

# ── Build domain list ────────────────────────────────────────────────────────

if [ -n "$CTXMILL_ALLOWED_EGRESS_DOMAINS" ]; then
  echo "# Generated from CTXMILL_ALLOWED_EGRESS_DOMAINS env var" > "$DOMAINS_FILE"
  echo "$CTXMILL_ALLOWED_EGRESS_DOMAINS" | tr ',' '\n' | while read -r domain; do
    domain=$(echo "$domain" | tr -d '[:space:]')
    [ -n "$domain" ] && echo "$domain" >> "$DOMAINS_FILE"
  done
fi

# ── Generate stream map ─────────────────────────────────────────────────────

{
  echo "# Auto-generated by entrypoint.sh — do not edit"
  echo "map \$ssl_preread_server_name \$upstream {"
  echo ""

  # Read domains from config file, skip comments and blank lines
  while IFS= read -r line; do
    # Strip leading/trailing whitespace
    domain=$(echo "$line" | tr -d '[:space:]')
    # Skip empty lines and comments
    case "$domain" in
      ""|\#*) continue ;;
    esac
    printf "    %-45s %s;\n" "$domain" "${domain}:443"
  done < "$DOMAINS_FILE"

  echo ""
  echo "    # Default: deny all other destinations"
  echo "    default                                       deny;"
  echo "}"
} > "$MAP_FILE"

echo "[egress-proxy] Generated stream map with $(grep -c ':443' "$MAP_FILE") allowed domain(s):"
grep ':443' "$MAP_FILE" | sed 's/^/  /'

# ── Start nginx ──────────────────────────────────────────────────────────────

exec nginx -g 'daemon off;'
