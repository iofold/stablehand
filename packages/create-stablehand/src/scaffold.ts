import { randomBytes } from 'node:crypto';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_TEMPLATE, findTemplate, TEMPLATES, type TemplateDefinition } from './templates.js';

export interface ScaffoldOptions {
  projectDir: string;
  packageName: string;
  /** Template name; see TEMPLATES. Defaults to "assistant". */
  template?: string;
  /** Written into .env when set. */
  openaiApiKey?: string;
  /** Image tag the generated compose file defaults to. */
  imageTag?: string;
  /** Where the template directories live (tests point this at the source tree). */
  templatesDir?: string;
}

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TEXT_EXTENSIONS = new Set(['.ts', '.yaml', '.yml', '.json', '.md', '.txt', '']);

/** This package's version: generated projects default to the images published with it. */
export function packageVersion(): string {
  const pkg = JSON.parse(readFileSync(join(PACKAGE_ROOT, 'package.json'), 'utf8')) as { version: string };
  return pkg.version;
}

function render(text: string, values: Record<string, string>): string {
  return text.replace(/\{\{(\w+)\}\}/g, (match, key: string) => values[key] ?? match);
}

function extensionOf(name: string): string {
  const dot = name.lastIndexOf('.');
  return dot > 0 ? name.slice(dot) : '';
}

/** Copy a template directory, rendering {{placeholders}} in text files. */
function copyTemplateDir(source: string, target: string, values: Record<string, string>): void {
  mkdirSync(target, { recursive: true });
  for (const entry of readdirSync(source, { withFileTypes: true })) {
    const from = join(source, entry.name);
    // npm drops .gitignore from published packages, so templates ship it as _gitignore.
    const to = join(target, entry.name.startsWith('_') ? `.${entry.name.slice(1)}` : entry.name);
    if (entry.isDirectory()) {
      copyTemplateDir(from, to, values);
    } else if (TEXT_EXTENSIONS.has(extensionOf(entry.name))) {
      writeFileSync(to, render(readFileSync(from, 'utf8'), values));
    } else {
      copyFileSync(from, to);
    }
  }
}

function packageJson(packageName: string, template: TemplateDefinition, version: string): string {
  const range = `^${version}`;
  return `${JSON.stringify({
    name: packageName,
    version: '0.1.0',
    type: 'module',
    private: true,
    scripts: {
      dev: 'docker compose up -d',
      'dev:down': 'docker compose down',
      'dev:logs': 'docker compose logs -f',
      ...template.scripts,
      test: 'vitest run',
      typecheck: 'tsc --noEmit',
    },
    dependencies: {
      '@stablehand/manifest': range,
      stablehand: range,
      zod: '^4.3.6',
    },
    devDependencies: {
      '@types/node': '^22.0.0',
      typescript: '^5.8.0',
      vitest: '^3.0.0',
    },
  }, null, 2)}\n`;
}

function envFile(template: TemplateDefinition, secrets: { masterKey: string; apiToken: string; webhookSecret: string }, openaiApiKey: string): string {
  return [
    '# Generated by create-stablehand. Keep it out of git (.gitignore lists it).',
    '',
    '# Provider key for the agents. Agents read it as $secret:OPENAI_API_KEY or by default.',
    `OPENAI_API_KEY=${openaiApiKey}`,
    'ANTHROPIC_API_KEY=',
    '',
    '# Encrypts per-agent secrets; the operator token for the UI and API.',
    `SECRET_MASTER_KEY=${secrets.masterKey}`,
    `STABLEHAND_API_TOKEN=${secrets.apiToken}`,
    `GALLERY_WEBHOOK_SECRET=${secrets.webhookSecret}`,
    '',
    '# Image tag: this project defaults to the release it was created with.',
    '# STABLEHAND_IMAGE_TAG=latest',
    '# UI_PORT=3200',
    '# API_PORT=3002',
    ...template.env,
    '',
  ].join('\n');
}

function envExample(template: TemplateDefinition): string {
  return [
    'OPENAI_API_KEY=',
    'ANTHROPIC_API_KEY=',
    '# openssl rand -hex 32',
    'SECRET_MASTER_KEY=',
    'STABLEHAND_API_TOKEN=',
    'GALLERY_WEBHOOK_SECRET=',
    ...template.env.map((line) => line.replace(/^(GALLERY_API_KEY)=.*/, '$1=')),
    '',
  ].join('\n');
}

function readme(packageName: string, template: TemplateDefinition): string {
  return `# ${packageName}

A [Stablehand](https://github.com/iofold/stablehand) project from the \`${template.name}\` template: ${template.description.toLowerCase()}.

## Run it

You need Docker with Compose. \`.env\` already holds generated secrets; add \`OPENAI_API_KEY\` if it is blank.

\`\`\`bash
${template.nextSteps.map((step) => (step.startsWith('open ') ? `# ${step}` : step)).join('\n')}
\`\`\`

The stack runs on prebuilt images (\`ghcr.io/iofold/stablehand-*\`). \`agents/\` and \`tools/\` are mounted into the orchestrator, which registers them at startup; after editing them run \`docker compose restart orchestrator\`.

## Layout

\`\`\`text
agents/<name>/agent.yaml   agent manifests (apiVersion: stablehand.io/v1)
tools/                     local tools, one defineTool() per file
tests/                     vitest checks for the manifests
docker-compose.yml         the stack
\`\`\`

## Commands

- \`npm test\` checks the manifests; \`npm run typecheck\` type-checks the tools.
- \`npm run dev\`, \`npm run dev:down\`, \`npm run dev:logs\` start, stop and tail the stack.
`;
}

export function scaffold(options: ScaffoldOptions): TemplateDefinition {
  const templateName = options.template ?? DEFAULT_TEMPLATE;
  const template = findTemplate(templateName);
  if (!template) {
    throw new Error(
      `Unknown template "${templateName}". Available: ${TEMPLATES.map((t) => t.name).join(', ')}`,
    );
  }
  const templatesDir = options.templatesDir ?? join(PACKAGE_ROOT, 'templates');
  const version = packageVersion();
  const values = {
    packageName: options.packageName,
    imageTag: options.imageTag ?? version,
  };

  copyTemplateDir(join(templatesDir, '_base'), options.projectDir, values);
  copyTemplateDir(join(templatesDir, template.name), options.projectDir, values);
  mkdirSync(join(options.projectDir, '.stablehand'), { recursive: true });

  const secrets = {
    masterKey: randomBytes(32).toString('hex'),
    apiToken: randomBytes(32).toString('hex'),
    webhookSecret: randomBytes(24).toString('hex'),
  };
  writeFileSync(join(options.projectDir, 'package.json'), packageJson(options.packageName, template, version));
  writeFileSync(join(options.projectDir, '.env'), envFile(template, secrets, options.openaiApiKey ?? ''), { mode: 0o600 });
  writeFileSync(join(options.projectDir, '.env.example'), envExample(template));
  writeFileSync(join(options.projectDir, 'README.md'), readme(options.packageName, template));
  return template;
}
