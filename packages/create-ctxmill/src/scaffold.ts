import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export interface ScaffoldOptions {
  projectDir: string;
  packageName: string;
  template?: string;
}

export function scaffold({ projectDir, packageName }: ScaffoldOptions): void {
  // Create project structure
  mkdirSync(join(projectDir, 'agents', 'assistant'), { recursive: true });
  mkdirSync(join(projectDir, 'tools'), { recursive: true });
  mkdirSync(join(projectDir, 'tests'), { recursive: true });
  mkdirSync(join(projectDir, '.ctxmill'), { recursive: true });

  writeFileSync(
    join(projectDir, 'package.json'),
    JSON.stringify(
      {
        name: packageName,
        version: '0.1.0',
        type: 'module',
        private: true,
        scripts: {
          dev: 'docker compose up --build',
          'dev:down': 'docker compose down',
          'dev:logs': 'docker compose logs -f',
          test: 'vitest run',
          typecheck: 'tsc --noEmit',
          chat: 'docker compose exec orchestrator npx ctxmill chat',
        },
        dependencies: {
          ctxmill: '^0.1.0',
          zod: '^3.24.0',
        },
        devDependencies: {
          typescript: '^5.8.0',
          vitest: '^3.0.0',
        },
      },
      null,
      2,
    ),
  );

  writeFileSync(
    join(projectDir, 'tsconfig.json'),
    JSON.stringify(
      {
        compilerOptions: {
          target: 'ES2024',
          module: 'NodeNext',
          moduleResolution: 'NodeNext',
          strict: true,
          esModuleInterop: true,
          skipLibCheck: true,
          outDir: 'dist',
          rootDir: '.',
        },
        include: [
          'tools/**/*.ts',
          'tests/**/*.ts',
          'vitest.config.ts',
        ],
      },
      null,
      2,
    ),
  );

  writeFileSync(
    join(projectDir, 'vitest.config.ts'),
    `import { defineConfig } from 'vitest/config';

export default defineConfig({
  test: {
    environment: 'node',
  },
});
`,
  );

  writeFileSync(
    join(projectDir, 'agents', 'assistant', 'agent.yaml'),
    `apiVersion: ctxmill.io/v1
kind: Agent
metadata:
  name: assistant
  displayName: Assistant
  description: Starter assistant generated by create-ctxmill.
  labels:
    harness: langgraph
    starter: default
spec:
  harness: langgraph
  harnessConfig:
    provider: openai
    model: gpt-5.4-mini
    apiKeyRef: "$secret:OPENAI_API_KEY"
  instructions: |
    You are a helpful AI assistant powered by CTXMill.

    Instructions:
    - Use available tools to help the user.
    - Be concise and helpful.
    - Use list-directory and read-file to explore the project structure when asked.
    - Use search-files to find relevant information across project files.
  tools:
    - ref: read-file
    - ref: list-directory
    - ref: search-files
  nativeTools:
    blocklist:
      - execute
  mode: interactive
  resources:
    maxSessionDurationSeconds: 120
    maxTokensPerSession: 4000
`,
  );

  writeFileSync(
    join(projectDir, 'tools', 'read-file.ts'),
    `import { defineTool } from 'ctxmill';
import { z } from 'zod';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const readFileInput = z.object({
  path: z.string().describe('Relative file path to read'),
});

export default defineTool({
  name: 'read-file',
  description: 'Read the contents of a file',
  input: readFileInput,
  async handler(input, ctx) {
    const { path: filePath } = readFileInput.parse(input);
    const basePath = resolve(ctx.workspaceDir);
    const resolved = resolve(basePath, filePath);
    if (resolved !== basePath && !resolved.startsWith(\`\${basePath}/\`)) {
      return 'Error: Cannot read files outside the project directory';
    }
    try {
      const content = await readFile(resolved, 'utf-8');
      return content.length > 10000
        ? content.slice(0, 10000) + '\\n... (truncated)'
        : content;
    } catch (err) {
      return \`Error reading file: \${(err as Error).message}\`;
    }
  },
});
`,
  );

  writeFileSync(
    join(projectDir, 'tools', 'list-directory.ts'),
    `import { defineTool } from 'ctxmill';
import { z } from 'zod';
import { readdir, stat } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const listDirectoryInput = z.object({
  path: z.string().default('.').describe('Directory path relative to project root'),
});

export default defineTool({
  name: 'list-directory',
  description: 'List files and directories in a path',
  input: listDirectoryInput,
  async handler(input, ctx) {
    const { path: dirPath } = listDirectoryInput.parse(input);
    const basePath = resolve(ctx.workspaceDir);
    const resolved = resolve(basePath, dirPath);
    if (resolved !== basePath && !resolved.startsWith(\`\${basePath}/\`)) {
      return 'Error: Cannot access directories outside the project';
    }
    try {
      const entries = await readdir(resolved, { withFileTypes: true });
      const lines = await Promise.all(
        entries
          .filter(e => !e.name.startsWith('.') && e.name !== 'node_modules')
          .slice(0, 100)
          .map(async (e) => {
            const fullPath = join(resolved, e.name);
            const s = await stat(fullPath).catch(() => null);
            const size = s ? (s.isDirectory() ? 'dir' : \`\${s.size}b\`) : '?';
            return \`\${e.isDirectory() ? 'DIR' : 'FILE'} \${e.name} (\${size})\`;
          })
      );
      return lines.join('\\n') || '(empty directory)';
    } catch (err) {
      return \`Error: \${(err as Error).message}\`;
    }
  },
});
`,
  );

  writeFileSync(
    join(projectDir, 'tools', 'search-files.ts'),
    `import { defineTool } from 'ctxmill';
import { z } from 'zod';
import { readdir, readFile } from 'node:fs/promises';
import { resolve, join, relative } from 'node:path';

const searchFilesInput = z.object({
  pattern: z.string().describe('Text or regex pattern to search for'),
  directory: z.string().default('.').describe('Directory to search in'),
  fileExtensions: z.array(z.string()).optional().describe('File extensions to include'),
});

export default defineTool({
  name: 'search-files',
  description: 'Search for text patterns across project files',
  input: searchFilesInput,
  async handler(input, ctx) {
    const { pattern, directory, fileExtensions } = searchFilesInput.parse(input);
    const basePath = resolve(ctx.workspaceDir);
    const searchDir = resolve(basePath, directory);
    if (searchDir !== basePath && !searchDir.startsWith(\`\${basePath}/\`)) {
      return 'Error: Cannot search outside the project';
    }
    const regex = new RegExp(pattern, 'gi');
    const results: string[] = [];

    async function walk(dir: string, depth = 0): Promise<void> {
      if (depth > 5 || results.length > 50) return;
      const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
      for (const entry of entries) {
        if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
        const full = join(dir, entry.name);
        if (entry.isDirectory()) {
          await walk(full, depth + 1);
        } else {
          if (fileExtensions && !fileExtensions.some(ext => entry.name.endsWith(ext))) continue;
          try {
            const content = await readFile(full, 'utf-8');
            const lines = content.split('\\n');
            for (let i = 0; i < lines.length; i++) {
              if (regex.test(lines[i])) {
                results.push(\`\${relative(basePath, full)}:\${i + 1}: \${lines[i].trim()}\`);
                if (results.length >= 50) return;
              }
              regex.lastIndex = 0;
            }
          } catch { /* skip binary files */ }
        }
      }
    }

    await walk(searchDir);
    return results.length > 0
      ? \`Found \${results.length} matches:\\n\${results.join('\\n')}\`
      : 'No matches found';
  },
});
`,
  );

  writeFileSync(
    join(projectDir, 'Dockerfile'),
    `FROM node:22-slim

WORKDIR /app

COPY package*.json ./
RUN npm install

COPY . .

EXPOSE 3001

CMD ["npx", "ctxmill", "dev"]
`,
  );

  writeFileSync(
    join(projectDir, 'docker-compose.yml'),
    `services:
  orchestrator:
    build: .
    environment:
      DATABASE_URL: \${DATABASE_URL:-postgres://ctxmill:ctxmill@postgres:5432/ctxmill}
      CTXMILL_PORT: 3001
      CTXMILL_UI_MODE: disabled
      CTXMILL_API_URL: http://localhost:3001
      OPENAI_API_KEY: \${OPENAI_API_KEY:-}
      ANTHROPIC_API_KEY: \${ANTHROPIC_API_KEY:-}
    depends_on:
      postgres:
        condition: service_healthy
    ports:
      - "3002:3001"
    volumes:
      - .:/app
      - node_modules:/app/node_modules
      - ctxmill_data:/app/.ctxmill

  postgres:
    image: postgres:16-alpine
    environment:
      POSTGRES_DB: ctxmill
      POSTGRES_USER: ctxmill
      POSTGRES_PASSWORD: ctxmill
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U ctxmill -d ctxmill"]
      interval: 5s
      timeout: 5s
      retries: 20
    ports:
      - "5433:5432"
    volumes:
      - postgres_data:/var/lib/postgresql/data

volumes:
  postgres_data:
  node_modules:
  ctxmill_data:
`,
  );

  writeFileSync(
    join(projectDir, '.dockerignore'),
    `node_modules/
dist/
.ctxmill/
.git/
`,
  );

  writeFileSync(
    join(projectDir, 'tests', 'assistant.test.ts'),
    `import { readFile } from 'node:fs/promises';
import { describe, it, expect } from 'vitest';
import { parseManifestString, validateManifest } from 'ctxmill';

describe('Assistant Agent', () => {
  it('agent manifest is valid', async () => {
    const manifestUrl = new URL('../agents/assistant/agent.yaml', import.meta.url);
    const raw = await readFile(manifestUrl, 'utf-8');
    const manifest = validateManifest(parseManifestString(raw));

    expect(manifest.metadata.name).toBe('assistant');
    expect(manifest.spec.harness).toBe('langgraph');
    expect(manifest.spec.harnessConfig).toMatchObject({
      provider: 'openai',
      model: 'gpt-5.4-mini',
      apiKeyRef: '$secret:OPENAI_API_KEY',
    });
    expect(manifest.spec.tools).toEqual([
      { ref: 'read-file' },
      { ref: 'list-directory' },
      { ref: 'search-files' },
    ]);
  });
});
`,
  );

  writeFileSync(
    join(projectDir, '.gitignore'),
    `node_modules/
dist/
.env
.ctxmill/
*.tsbuildinfo
`,
  );

  writeFileSync(
    join(projectDir, '.env.example'),
    `# Database used by docker compose
DATABASE_URL=postgres://ctxmill:ctxmill@postgres:5432/ctxmill

# Model and API key used by the starter LangGraph agent
OPENAI_MODEL=gpt-5.4-mini
OPENAI_API_KEY=sk-...
ANTHROPIC_API_KEY=

# Optional: custom base URL (for proxies)
# OPENAI_BASE_URL=https://api.openai.com/v1
`,
  );

  writeFileSync(
    join(projectDir, 'README.md'),
    `# ${packageName}

Built with [CTXMill](https://github.com/ctxmill/ctxmill) -- the framework for vertical AI products.

## Quick Start

\`\`\`bash
cp .env.example .env
# add your API keys to .env
docker compose up --build
\`\`\`

The API will be available at http://localhost:3002.

To chat with your agent from the running container:

\`\`\`bash
docker compose exec orchestrator npx ctxmill chat
\`\`\`

## Project Structure

\`\`\`
${packageName}/
  agents/assistant/agent.yaml  # Agent manifest
  tools/read-file.ts           # Tool implementations
  tests/                       # Tests
\`\`\`

## Commands

- \`npm run dev\` -- Build and start the Docker stack
- \`npm run dev:down\` -- Stop the Docker stack
- \`npm run dev:logs\` -- Tail container logs
- \`npm run chat\` -- Open terminal chat inside the orchestrator container
- \`npx vitest\` -- Run tests
- \`npm run typecheck\` -- Type-check project TypeScript
`,
  );
}
